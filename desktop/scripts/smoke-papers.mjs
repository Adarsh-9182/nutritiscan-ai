// Native UI check using fictional documents. No model or clinical service calls.
import { _electron as electron } from "playwright-core";
import { createRequire } from "node:module";
import fs from "node:fs/promises";
import path from "node:path";
import os from "node:os";
import assert from "node:assert/strict";
const require = createRequire(import.meta.url), appArgument = process.argv.find((arg) => arg.startsWith("--app="))?.slice(6);
const packaged = Boolean(appArgument), binary = packaged ? path.join(path.resolve(appArgument), "Contents/MacOS/NutritiScan") : require("electron");
const directory = await fs.mkdtemp(path.join(os.tmpdir(), "nutritiscan-papers-ui-")), output = path.resolve("test-results"); await fs.mkdir(output, { recursive: true });
const picked = path.join(directory, "picked-paper.pdf"); await fs.copyFile("resources/sample-paper.pdf", picked);
const launch = () => electron.launch({ executablePath: binary, args: packaged ? [] : [path.resolve(".")], env: { ...process.env, ...(process.argv.includes("--finder-env") ? { PATH: "/usr/bin:/bin:/usr/sbin:/sbin" } : {}), NUTRITISCAN_DATA_DIR: directory } });
let app, stage = "launch";
try {
  app = await launch(); const page = await app.firstWindow(); const errors = []; page.on("pageerror", (error) => errors.push(error.message));
  await page.getByRole("button", { name: "Explore the sample project", exact: true }).click();
  await page.getByRole("tab", { name: "Papers", exact: true }).click();
  stage = "native-pdf-import";
  await app.evaluate(({ dialog }, filename) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [filename] }); }, picked);
  await page.getByRole("button", { name: "Import a PDF from this Mac", exact: true }).click();
  const reader = page.getByRole("dialog", { name: "Paper reader", exact: true }); await reader.waitFor();
  await reader.getByAltText("Original PDF page 1", { exact: true }).waitFor();
  await reader.getByLabel("Paper section", { exact: true }).selectOption("p2");
  await reader.getByAltText("Original PDF page 2", { exact: true }).waitFor();
  assert.match(await reader.locator(".paper-extracted").innerText(), /mean signal was 5/);
  await reader.getByRole("button", { name: "100%", exact: true }).click();
  assert.ok((await reader.getByAltText("Original PDF page 2", { exact: true }).boundingBox()).width >= 1000);
  await reader.getByRole("button", { name: "Fit page", exact: true }).click();
  await page.screenshot({ path: path.join(output, "paper-reader-light.png") });
  stage = "literal-search-and-quote-check";
  await reader.getByRole("textbox", { name: "Search this paper", exact: true }).fill("mean signal");
  await reader.getByRole("button", { name: "Search", exact: true }).click();
  await reader.locator(".paper-search-results button").filter({ hasText: "PDF page 2" }).click();
  assert.match(await reader.locator(".paper-extracted mark").innerText(), /mean signal/i);
  await reader.getByText("Check a quotation against this section", { exact: true }).click();
  await reader.getByRole("textbox", { name: "Proposed finding", exact: true }).fill("This fictional note states the constructed group means.");
  await reader.getByRole("textbox", { name: "Exact quotation", exact: true }).fill("This fabricated quotation does not exist in the source.");
  await reader.getByRole("button", { name: "Check passage membership", exact: true }).click();
  await reader.locator(".paper-check-result").filter({ hasText: "Withheld" }).waitFor();
  const quote = "The mean signal was 5 in model_A and 12 in model_B.";
  await reader.getByRole("textbox", { name: "Exact quotation", exact: true }).fill(quote);
  await reader.getByRole("button", { name: "Check passage membership", exact: true }).click();
  await reader.locator(".paper-check-result").filter({ hasText: "Passage found" }).waitFor();
  stage = "blank-page-and-small-layout";
  await reader.getByLabel("Paper section", { exact: true }).selectOption("p3");
  await reader.getByRole("heading", { name: "No readable text layer", exact: true }).waitFor();
  await reader.getByAltText("Original PDF page 3", { exact: true }).waitFor();
  await page.setViewportSize({ width: 800, height: 900 });
  await reader.getByLabel("Paper section", { exact: true }).selectOption("p2");
  await reader.getByAltText("Original PDF page 2", { exact: true }).waitFor();
  assert.equal(await reader.evaluate((el) => el.scrollWidth > el.clientWidth), false);
  await page.screenshot({ path: path.join(output, "paper-reader-800.png") });
  await reader.getByRole("button", { name: "Close paper reader", exact: true }).click();
  stage = "checked-passage-navigation";
  await page.getByRole("button", { name: "Open cited passage →", exact: true }).last().click();
  await reader.locator(".paper-extracted mark").waitFor();
  assert.equal(await reader.locator(".paper-extracted mark").innerText(), quote);
  await reader.getByRole("button", { name: "Close paper reader", exact: true }).click();
  stage = "saved-report-inline-citation";
  const state = await page.evaluate(async () => (await window.biology.call("state")).value), paper = state.project.papers[0];
  await fs.mkdir(path.join(directory, "sample-project/artifacts"), { recursive: true });
  await fs.writeFile(path.join(directory, "sample-project/artifacts/paper-review.md"), `# Fictional paper review\n\nSynthetic software test only. [Open evidence](nutritiscan://paper/${paper.id}/p2).\n`);
  await page.getByRole("tab", { name: "Files", exact: true }).click(); await page.getByRole("button", { name: "Refresh files", exact: true }).click();
  await page.getByRole("button", { name: "Open saved report paper-review.md", exact: true }).click();
  await page.getByRole("link", { name: "Open evidence", exact: true }).click();
  await reader.getByAltText("Original PDF page 2", { exact: true }).waitFor();
  await reader.getByRole("button", { name: "Close paper reader", exact: true }).click();
  await page.getByRole("button", { name: "Switch to dark mode", exact: true }).click();
  await page.getByRole("tab", { name: "Papers", exact: true }).click();
  await page.getByRole("button", { name: "Open paper →", exact: true }).click(); await reader.getByAltText("Original PDF page 1", { exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, "paper-reader-dark.png") });
  await reader.getByRole("button", { name: "Close paper reader", exact: true }).click();
  stage = "session-export";
  const exportPath = path.join(directory, "export.md"); await app.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath }); }, exportPath);
  await page.getByRole("button", { name: "Export", exact: true }).click();
  await page.getByText("Research export requested.", { exact: true }).waitFor();
  const exported = await fs.readFile(exportPath, "utf8"); assert.ok(exported.includes(paper.sourceSha256)); assert.ok(exported.includes(quote));
  stage = "restart";
  await app.close(); app = await launch(); const restored = await app.firstWindow();
  await restored.getByRole("tab", { name: "Papers", exact: true }).click();
  await restored.getByRole("button", { name: "Open cited passage →", exact: true }).last().click();
  await restored.getByRole("dialog", { name: "Paper reader", exact: true }).getByAltText("Original PDF page 2", { exact: true }).waitFor();
  const saved = JSON.parse(await fs.readFile(path.join(directory, "workspace.json"), "utf8"));
  assert.equal(saved.projects[0].papers.length, 1); assert.equal(saved.projects[0].sessions[0].paperChecks.length, 2); assert.deepEqual(errors, []);
  const pmcid = process.argv.find((arg) => arg.startsWith("--pmc="))?.slice(6);
  if (pmcid) {
    stage = "live-PMC-import";
    await restored.getByRole("button", { name: "Close paper reader", exact: true }).click();
    await restored.getByRole("textbox", { name: "PMC identifier", exact: true }).fill(pmcid);
    await restored.getByRole("button", { name: "Fetch open full text", exact: true }).click();
    const pmcReader = restored.getByRole("dialog", { name: "Paper reader", exact: true });
    await pmcReader.waitFor({ timeout: 35000 });
    await pmcReader.getByLabel("Paper section", { exact: true }).selectOption("s3");
    await pmcReader.locator(".paper-extracted").filter({ hasText: /\S/ }).waitFor();
    assert.equal(await pmcReader.locator(".paper-original").count(), 0);
    await pmcReader.getByText("Source, licence and extraction limits", { exact: true }).click();
    await pmcReader.locator(".paper-reader-footer").filter({ hasText: "CC BY" }).waitFor();
    await restored.screenshot({ path: path.join(output, "pmc-reader.png") });
  }
  console.log(JSON.stringify({ passed: true, packaged, modelCalls: 0, livePmc: pmcid ?? null, checks: ["native-picker-import", "original-PDF-and-extracted-page", "page-zoom", "literal-search-highlight", "withheld-and-matching-quotes", "blank-page-retained", "800px-reader", "light/dark", "inline-report-citation", "session-export", "restart", "no-renderer-errors"] }));
} catch (error) { console.error(JSON.stringify({ passed: false, stage, error: error.message })); if (app) await (await app.firstWindow()).screenshot({ path: path.join(output, "paper-reader-failure.png") }).catch(() => {}); process.exitCode = 1; }
finally { await app?.close().catch(() => {}); await fs.rm(directory, { recursive: true, force: true }); }
